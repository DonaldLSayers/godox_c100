#!/usr/bin/env python3
"""Film simulations (HaldCLUT 3D LUTs) and two ways to combine them with a
palette.

A film simulation is a 3D lookup table: every input RGB -> an output RGB,
measured from (or matched to) a film stock. The G'MIC packs in film_luts/
(Pat David's, from gmic.eu/color_presets; not committed) are HaldCLUT PNGs of
level 8: a 512x512 image holding a 64^3 cube, red fastest, then green, then
blue. Pillow reads them as 8-bit, which is plenty here.

The two approaches, for a palette P (endesga32 by default):
  film -> P   apply the film to the photo, then nearest colour in P, as the
              camera does today. On the camera this means a film-transformed
              lookup table (needs the film's cube on the camera).
  P -> film   nearest colour in P on the untouched photo, then paint each
              block with film(colour) instead of the colour itself: the film
              applied to the 32 palette colours. On the camera: a second,
              per-film table of 32 display colours (96 B), nothing else.

  film.py LUT.png IN.jpg OUT.png    apply a film to a photo (no palette)
  film.py gen                       write film_colours.py: the presets' film
                                    colours (palettes.py PRESETS with a film)
"""
import glob, os, sys
import numpy as np
from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'film_luts')


def load(path):
    """HaldCLUT PNG -> float cube [b, g, r, 3] in 0..1."""
    a = np.asarray(Image.open(path).convert('RGB'), dtype=np.float32) / 255
    n = round((a.shape[0] * a.shape[1]) ** (1 / 3))
    assert n ** 3 == a.shape[0] * a.shape[1], f'{path}: not a HaldCLUT'
    return a.reshape(n, n, n, 3)


def apply(cube, rgb):
    """Trilinear lookup of uint8 RGB values (any shape [..., 3]) -> uint8."""
    n = cube.shape[0]
    x = rgb.astype(np.float32) / 255 * (n - 1)
    i0 = np.clip(np.floor(x).astype(int), 0, n - 2)
    f = x - i0
    r0, g0, b0 = i0[..., 0], i0[..., 1], i0[..., 2]
    fr, fg, fb = f[..., 0:1], f[..., 1:2], f[..., 2:3]
    out = 0
    for db, wb in ((0, 1 - fb), (1, fb)):
        for dg, wg in ((0, 1 - fg), (1, fg)):
            for dr, wr in ((0, 1 - fr), (1, fr)):
                out = out + wb * wg * wr * cube[b0 + db, g0 + dg, r0 + dr]
    return np.clip(np.round(out * 255), 0, 255).astype(np.uint8)


def apply_img(cube, img):
    return Image.fromarray(apply(cube, np.asarray(img.convert('RGB'))))


def apply_hex(cube, hexes):
    rgb = np.array([[int(h[i:i + 2], 16) for i in (0, 2, 4)] for h in hexes], dtype=np.uint8)
    return [''.join(f'{v:02X}' for v in c) for c in apply(cube, rgb)]


def gen(path=os.path.join(os.path.dirname(os.path.abspath(__file__)), 'film_colours.py')):
    from palettes import MATCH, PRESETS, yuv_to_hex
    luts = {os.path.splitext(os.path.basename(f))[0]: f for f in glob.glob(os.path.join(ROOT, '*', '*.png'))}
    filmed = [(tag, [yuv_to_hex(c) for c in MATCH[p]], film) for tag, p, film in PRESETS if film]
    lines = ['"""Generated by tools/film.py gen -- do not edit.',
             '',
             'DISPLAY[tag]: the film colours of each preset that has a film, index for',
             'index with its match palette (SOURCE[tag], the colours the film was applied',
             'to; palettes.py checks they are still the same). Films: '
             + ', '.join(f'{tag} = {film}' for tag, _, film in filmed) + '.',
             '"""', '', 'SOURCE = {']
    lines += [f'    {tag!r}: {hx!r},' for tag, hx, _ in filmed] + ['}', '', 'DISPLAY = {']
    lines += [f'    {tag!r}: {apply_hex(load(luts[film]), hx)!r},' for tag, hx, film in filmed]
    lines.append('}')
    open(path, 'w').write('\n'.join(lines) + '\n')
    print(path)


if __name__ == '__main__':
    if sys.argv[1:] == ['gen']:
        gen()
    else:
        apply_img(load(sys.argv[1]), Image.open(sys.argv[2])).save(sys.argv[3])
